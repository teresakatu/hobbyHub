-- ---------------------------------------------------------------
-- Tables
-- ---------------------------------------------------------------
create table if not exists public.posts (
  id          bigint generated by default as identity primary key,
  created_at  timestamptz not null default now(),
  title       text        not null check (char_length(trim(title)) > 0),
  content     text        default '',
  image_url   text        default '',
  video_url   text        default '',
  flag        text        check (flag in ('Question', 'Opinion', 'Recipe', 'Gear', 'Showcase')),
  upvotes     integer     not null default 0,
  author_id   text,
  repost_of   bigint      references public.posts (id) on delete set null
);

create table if not exists public.comments (
  id          bigint generated by default as identity primary key,
  created_at  timestamptz not null default now(),
  post_id     bigint      not null references public.posts (id) on delete cascade,
  content     text        not null,
  author_id   text
);

create index if not exists comments_post_id_idx on public.comments (post_id);
create index if not exists posts_repost_of_idx on public.posts (repost_of);

-- The course instructions use tables without Row Level Security.
alter table public.posts disable row level security;
alter table public.comments disable row level security;

grant select, insert, update, delete on public.posts, public.comments to anon, authenticated;
grant usage, select on all sequences in schema public to anon, authenticated;

-- ---------------------------------------------------------------
-- Atomic upvote (so two quick clicks never overwrite each other)
-- ---------------------------------------------------------------
create or replace function public.increment_upvotes(row_id bigint)
returns integer
language sql
as $$
  update public.posts set upvotes = upvotes + 1 where id = row_id returning upvotes;
$$;

grant execute on function public.increment_upvotes(bigint) to anon, authenticated;

-- ---------------------------------------------------------------
-- OPTIONAL: storage bucket for "upload image from your computer".
-- If you skip this, uploaded images are stored inline in image_url instead.
-- ---------------------------------------------------------------
insert into storage.buckets (id, name, public)
values ('post-images', 'post-images', true)
on conflict (id) do nothing;

drop policy if exists "Anyone can upload post images" on storage.objects;
create policy "Anyone can upload post images"
  on storage.objects for insert to anon, authenticated
  with check (bucket_id = 'post-images');

drop policy if exists "Anyone can view post images" on storage.objects;
create policy "Anyone can view post images"
  on storage.objects for select to anon, authenticated
  using (bucket_id = 'post-images');
